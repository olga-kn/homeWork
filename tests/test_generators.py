# Тестирование генератора card_number_generator
# Генератор выдает правильные номера карт в заданном диапазоне.
def test_card_number_generator():
    result = list(card_number_generator(1, 5))
    expected = ["0000 0000 0000 0001", "0000 0000 0000 0002", "0000 0000 0000 0003", "0000 0000 0000 0004"]
    assert result == expected


# Корректность форматирования номеров карт.
def test_card_number_generator():
    for card in card_number_generator(0, 10):
        assert len(card) == 19, "Неверная длина номера карты"
        assert card[4] == " " and card[9] == " " and card[14] == " ", "Неверное форматирование пробелов"


# Генератор корректно обрабатывает крайние значения диапазона и правильно завершает генерацию.
def test_card_number_generator():
    cards = list(card_number_generator(0, 2))
    assert cards[0] == "0000 0000 0000 0000", "Неверный первый номер карты"

    # Проверка конца диапазона
    assert cards[-1] == "0000 0000 0000 0001", "Неверный последний номер карты"

    # Проверка завершения генерации
    assert len(cards) == 2, "Неверное количество сгенерированных номеров"
